        """
        :ivar index: An index into the IP-XACT object.
        """

        index: Sequence[UnsignedIntExpression] = field(
            default_factory=list,
            metadata={
                "type": "Element",
                "namespace": "http://www.accellera.org/XMLSchema/IPXACT/1685-2014",
                "min_occurs": 1,
            },
        )
